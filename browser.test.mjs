import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createBrowser } from './browser.mjs';

test('real browser: snapshots, forms, popup tabs, screenshots, cross-turn and profile persistence', { skip: !process.env.POWER_TEST_BROWSER, timeout: 120000 }, async (t) => {
  const home = mkdtempSync(join(tmpdir(), 'power-browser-'));
  const web = createServer((req, res) => {
    res.setHeader('content-type', 'text/html');
    if (req.url === '/blocked') return res.end('<h1>Access denied</h1><p>Error 15: This request was blocked by our security service</p>');
    res.end('<title>Power browser fixture</title><label>Name<input id="name"></label><button>Save</button><h1>Ready</h1><a href="/popup" target="_blank">Open popup</a><input type="file" id="file"><script>document.querySelector("button").onclick=()=>{document.querySelector("h1").textContent=document.querySelector("input").value;localStorage.setItem("signedIn","yes")}</script>');
  }).listen(0, '127.0.0.1');
  await new Promise((r) => web.once('listening', r));
  let browser = createBrowser({ home, headless: !process.env.POWER_TEST_HEADED });
  t.after(async () => { await browser.close(); web.close(); rmSync(home, { recursive: true, force: true }); });
  const url = `http://127.0.0.1:${web.address().port}`;
  assert.equal((await browser.panel('start')).started, true);
  assert.equal((await browser.panel('frame')).started, true);
  const catalog = await browser.call('one', 'tools');
  assert.ok(catalog.some((x) => x.name === 'browser_navigate'));
  const navigate = await browser.call('one', 'browser_navigate', { url });
  assert.equal(navigate.isError, undefined, JSON.stringify(navigate));
  assert.match(navigate.content.map((x) => x.text || '').join(''), /Power browser fixture/);
  assert.ok(!(await browser.call('one', 'show')).isError);
  await assert.rejects(browser.call('two', 'browser_snapshot'), /另一个对话/);
  await browser.call('one', 'browser_fill_form', { fields: [{ target: '#name', name: 'Name', type: 'textbox', value: 'Power works' }] });
  const form = await browser.call('one', 'browser_click', { target: 'button' });
  assert.ok(!form.isError, JSON.stringify(form));
  assert.match(JSON.stringify(await browser.call('one', 'browser_snapshot')), /Power works/);
  const initialFrame = await browser.panel('frame');
  assert.equal(initialFrame.url, url + '/');
  assert.ok(Buffer.from(initialFrame.jpeg, 'base64').length > 100);
  assert.ok(initialFrame.width > 0 && initialFrame.height > 0);
  await assert.rejects(browser.panel('text', { text: 'wrong' }), /手动接管/);
  await browser.panel('takeover');
  await assert.rejects(browser.call('one', 'browser_snapshot'), /用户正在/);
  await assert.rejects(browser.panel('text', { pageId: -1, text: 'wrong' }), /网页已切换/);
  await browser.panel('click', { pageId: initialFrame.pageId, x: 70, y: 18 });
  await browser.panel('key', { pageId: initialFrame.pageId, key: process.platform === 'darwin' ? 'Meta+A' : 'Control+A' });
  await browser.panel('text', { pageId: initialFrame.pageId, text: '手动输入 works' });
  await assert.rejects(browser.panel('navigate', { pageId: initialFrame.pageId, url: 'javascript:alert(1)' }), /http/);
  await browser.panel('resume');
  assert.match(JSON.stringify(await browser.call('one', 'browser_snapshot')), /手动输入 works/);
  const screenshot = await browser.call('one', 'browser_take_screenshot', { type: 'png' });
  assert.ok(!screenshot.isError, JSON.stringify(screenshot));
  assert.ok(screenshot.content.some((x) => x.type === 'image'));
  const upload = join(home, 'attachment.txt'); writeFileSync(upload, 'user attachment');
  await browser.call('one', 'browser_click', { target: '#file' });
  const uploaded = await browser.call('one', 'browser_file_upload', { paths: [upload] });
  assert.ok(!uploaded.isError, JSON.stringify(uploaded));
  browser.release('one');
  const snapshot = await browser.call('two', 'browser_snapshot');
  assert.match(JSON.stringify(snapshot), /Power works/);
  const popup = await browser.call('two', 'browser_click', { target: 'a' });
  assert.ok(!popup.isError, JSON.stringify(popup));
  const tabs = await browser.call('two', 'browser_tabs', { action: 'list' });
  assert.match(JSON.stringify(tabs), /popup/);
  const popupFrame = await browser.panel('frame', { width: 640, height: 480 });
  assert.ok(popupFrame.width > 0);
  assert.match(popupFrame.url, /popup/);
  await browser.panel('takeover');
  const resized = await browser.panel('frame', { width: 640, height: 480 });
  assert.equal(resized.width, 640);
  const otherViewer = await browser.panel('frame', {width:1100,height:800});
  assert.equal(otherViewer.width,640, 'another viewer must not resize click targets');
  await browser.panel('tab', { id: initialFrame.pageId });
  assert.equal((await browser.panel('frame')).pageId, initialFrame.pageId);
  await browser.panel('navigate', { pageId: initialFrame.pageId, url: url + '/blocked' });
  assert.equal((await browser.panel('frame')).blocked, true);
  await browser.panel('resume');
  await browser.close();
  browser = createBrowser({ home, headless: !process.env.POWER_TEST_HEADED });
  await browser.call('three', 'browser_navigate', { url });
  const stored = await browser.call('three', 'browser_evaluate', { function: '() => localStorage.getItem("signedIn")' });
  assert.ok(!stored.isError, JSON.stringify(stored));
  assert.match(JSON.stringify(stored), /yes/);
});
